export type SpotLightGeometry = {
  vertexData: Float32Array;
  indexData: Uint16Array;
  indexCount: number;
};

/**
 * 创建一个只包含位置和法线的单位 box 几何。
 * @returns {SpotLightGeometry} 可直接送进 GPU 的顶点数据与索引数据。
 */
export function createSpotLightGeometry(): SpotLightGeometry {
  return {
    vertexData: new Float32Array([
      // right
      0.5, 0.5, 0.5, 1, 0, 0,
      0.5, 0.5, -0.5, 1, 0, 0,
      0.5, -0.5, 0.5, 1, 0, 0,
      0.5, -0.5, -0.5, 1, 0, 0,

      // left
      -0.5, 0.5, -0.5, -1, 0, 0,
      -0.5, 0.5, 0.5, -1, 0, 0,
      -0.5, -0.5, -0.5, -1, 0, 0,
      -0.5, -0.5, 0.5, -1, 0, 0,

      // top
      -0.5, 0.5, -0.5, 0, 1, 0,
      0.5, 0.5, -0.5, 0, 1, 0,
      -0.5, 0.5, 0.5, 0, 1, 0,
      0.5, 0.5, 0.5, 0, 1, 0,

      // bottom
      -0.5, -0.5, 0.5, 0, -1, 0,
      0.5, -0.5, 0.5, 0, -1, 0,
      -0.5, -0.5, -0.5, 0, -1, 0,
      0.5, -0.5, -0.5, 0, -1, 0,

      // front
      -0.5, 0.5, 0.5, 0, 0, 1,
      0.5, 0.5, 0.5, 0, 0, 1,
      -0.5, -0.5, 0.5, 0, 0, 1,
      0.5, -0.5, 0.5, 0, 0, 1,

      // back
      0.5, 0.5, -0.5, 0, 0, -1,
      -0.5, 0.5, -0.5, 0, 0, -1,
      0.5, -0.5, -0.5, 0, 0, -1,
      -0.5, -0.5, -0.5, 0, 0, -1,
    ]),
    indexData: new Uint16Array([
      0, 2, 1, 2, 3, 1,
      4, 6, 5, 6, 7, 5,
      8, 10, 9, 10, 11, 9,
      12, 14, 13, 14, 15, 13,
      16, 18, 17, 18, 19, 17,
      20, 22, 21, 22, 23, 21,
    ]),
    indexCount: 36,
  };
}
